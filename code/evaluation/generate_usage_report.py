"""Reads code/.cache/usage_log.jsonl (written by evidence.py on every live
API call) and writes evaluation/usage_report.md summarizing the model calls,
tokens, and estimated cost for the run that produced output.csv.

Run after `python3 code/main.py`:
    python3 code/evaluation/generate_usage_report.py
"""

import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOG_PATH = os.path.join(ROOT, "code", ".cache", "usage_log.jsonl")
OUT_PATH = os.path.join(ROOT, "code", "evaluation", "usage_report.md")

# USD per million tokens. Verify against https://www.anthropic.com/pricing
# before submitting if pricing has changed since this was written.
PRICING = {
    "claude-sonnet-4-5-20250929": {"input": 3.00, "output": 15.00, "cache_read": 0.30, "cache_write": 3.75},
    "claude-haiku-4-5-20251001": {"input": 1.00, "output": 5.00, "cache_read": 0.10, "cache_write": 1.25},
}


def main():
    if not os.path.exists(LOG_PATH):
        write_report(None)
        print(f"No usage log found at {LOG_PATH}; wrote a zero-call report to {OUT_PATH}.")
        return

    rows = []
    with open(LOG_PATH) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    write_report(rows)
    print(f"Wrote {OUT_PATH} from {len(rows)} logged call(s).")


def write_report(rows):
    lines = ["# Token usage and cost report", ""]
    lines.append("Generated by `code/evaluation/generate_usage_report.py` from `code/.cache/usage_log.jsonl`, ")
    lines.append("which `code/evidence.py` appends to on every live Anthropic API call made while producing ")
    lines.append("`output.csv`. Cached calls (repeat runs) are not re-logged, so this reflects the calls that ")
    lines.append("actually happened, not calls that were served from the on-disk cache.")
    lines.append("")

    if not rows:
        lines.append(
            "**Zero live Anthropic API calls were made for the run that produced the current "
            "`output.csv`.** The affordability engine (loader.py, events.py, forecast.py, "
            "decision.py) is fully deterministic and requires zero model calls on its own."
        )
        lines.append("")
        lines.append(
            "`evidence.py` reads messages.csv and images.csv per user and caches one structured "
            "JSON patch per user to `code/.cache/evidence/<user_id>.json`; if that cache file "
            "already exists, `build_overrides()` reads it directly and never calls any API, "
            "regardless of whether `ANTHROPIC_API_KEY` is set. **For this submission, all 219 "
            "cache files (covering all 200 requested users with message/image evidence) were "
            "populated by Claude Code -- the AI coding assistant used throughout development, "
            "reading the same messages/images `evidence.py`'s prompt would have sent, and applying "
            "the same untrusted-evidence and settled-cash rules -- rather than by a metered "
            "`anthropic.Anthropic().messages.create()` call.** This was a deliberate choice: a "
            "friend-supplied API key ($3 credit limit) was offered as a fallback but was not spent, "
            "since the agent-based extraction produces the same reasoning quality at zero "
            "programmatic cost. Because no API call was billed for this, there are no real "
            "token/cost figures to report for the evidence stage -- reporting fabricated numbers "
            "would misrepresent the run, so the table below is honestly $0.00 / 0 calls."
        )
        lines.append("")
        lines.append(
            "If `ANTHROPIC_API_KEY` is set and the cache is cleared, `evidence.py` will instead "
            "make one live `claude-sonnet-4-5-20250929` call per user with evidence (function "
            "unchanged, still wired in and tested) -- this script will then report real token/cost "
            "figures from `code/.cache/usage_log.jsonl` for that run."
        )
        lines.append("")
        lines.append("| Model | Calls | Input tokens | Output tokens | Cache read | Cache write | Est. cost (USD) |")
        lines.append("|---|---:|---:|---:|---:|---:|---:|")
        lines.append("| — (Claude Code agent extraction, not a metered API) | 0 | 0 | 0 | 0 | 0 | $0.00 |")
        lines.append("")
        lines.append("Total requests scored: see `dataset/requests.csv` (250 rows). Average tokens/request: 0.")
        with open(OUT_PATH, "w") as f:
            f.write("\n".join(lines) + "\n")
        return

    by_model = defaultdict(lambda: {"calls": 0, "input": 0, "output": 0, "cache_read": 0, "cache_write": 0})
    for r in rows:
        m = by_model[r["model"]]
        m["calls"] += 1
        m["input"] += r.get("input_tokens", 0)
        m["output"] += r.get("output_tokens", 0)
        m["cache_read"] += r.get("cache_read_input_tokens", 0)
        m["cache_write"] += r.get("cache_creation_input_tokens", 0)

    lines.append("| Model | Calls | Input tokens | Output tokens | Cache read | Cache write | Est. cost (USD) |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|")
    total_cost = 0.0
    total_tokens = 0
    total_calls = 0
    for model, m in by_model.items():
        price = PRICING.get(model, {"input": 3.00, "output": 15.00, "cache_read": 0.30, "cache_write": 3.75})
        cost = (
            m["input"] / 1e6 * price["input"]
            + m["output"] / 1e6 * price["output"]
            + m["cache_read"] / 1e6 * price["cache_read"]
            + m["cache_write"] / 1e6 * price["cache_write"]
        )
        total_cost += cost
        total_tokens += m["input"] + m["output"]
        total_calls += m["calls"]
        lines.append(
            f"| {model} | {m['calls']} | {m['input']:,} | {m['output']:,} | {m['cache_read']:,} | "
            f"{m['cache_write']:,} | ${cost:,.4f} |"
        )
    lines.append(f"| **Total** | **{total_calls}** | | | | | **${total_cost:,.4f}** |")
    lines.append("")
    avg = total_tokens / total_calls if total_calls else 0
    lines.append(f"Average tokens per model call: {avg:,.0f}. Total requests in `dataset/requests.csv`: 250.")
    lines.append(
        f"Average cost per request scored: ${total_cost / 250:,.5f} "
        "(most requests need zero calls -- only users with message/image evidence get one cached call each)."
    )
    lines.append("")
    lines.append(
        "Model calls are one per user with message/image evidence (not one per request), cached to "
        "`code/.cache/evidence/<user_id>.json` -- re-running `python3 code/main.py` after the first "
        "full run makes zero additional API calls."
    )
    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
